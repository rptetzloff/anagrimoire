// Emits SQL to seed public.blocked_names from the list we already keep for
// puzzle answers. Prints it; doesn't run it, and doesn't commit the words —
// schema.sql says keeping the repo clean of a names list is deliberate, and
// this respects that by writing to stdout for the SQL editor.
//
//   npm run name-blocklist > names.sql     (then paste, then delete)
//
// Two match kinds, because one size genuinely doesn't fit — the reasoning is
// in schema.sql and worth not re-deriving:
//
//   substring  rejects a name containing it anywhere. Right for slurs, which
//              must not appear at all. Wrong for everything else: "assassin",
//              "Cummings" and Penistone are real names, and a big list matched
//              this way rejects far more innocent people than abusive ones.
//   exact      rejects only the whole name. Safe for bulk, because it stops
//              the name being that word without ruining every name containing
//              it.
//
// So `both`-scope entries — the slurs — go in as substring, and everything
// else as exact. That mapping is not a coincidence: `both` already means "not
// even if you type it", which is the same judgement a substring match makes.

import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
// The same list the generator blocklist is built from — {word, origin, scope}.
// This read `blockedEntries()`, which was never defined or imported anywhere,
// so the script threw on line 26 and had never once run. Nothing noticed,
// because it is invoked by hand and prints SQL rather than applying it.
const words = require('../src/wordbands/blocked-words.json').words;

// Which slurs are actually safe to match anywhere in a name, computed rather
// than assumed. Mapping every `both` entry to substring looked right and was
// badly wrong: "abo" is inside about, above and laboratory; "spic" is inside
// suspicion and conspicuous; "coon" is inside raccoon and tycoon. That's the
// Scunthorpe problem the schema warns about, and it rejects far more innocent
// names than abusive ones.
//
// A pattern is safe only if every word containing it is one we'd block too —
// its own plural counts, since blocking "darkie" ought to catch "darkies".
const LEVELS = [10, 20, 35, 40, 50, 55, 60, 70];
const dictionary = new Set();
for (const level of LEVELS)
  for (const locale of ['english', 'american'])
    for (const raw of require(`wordlist-english/${locale}-words-${level}.json`)) {
      const w = String(raw).toLowerCase();
      if (/^[a-z]+$/.test(w)) dictionary.add(w);
    }

const blockedWords = new Set(words.map((w) => w.word));
const safeAnywhere = (p) =>
  ![...dictionary].some(
    (w) =>
      w !== p &&
      w !== `${p}s` &&
      w !== `${p}es` &&
      !blockedWords.has(w) &&
      w.includes(p)
  );

const slurs = words.filter((w) => w.scope === 'both').map((w) => w.word);
const substring = slurs.filter(safeAnywhere);
// A slur that isn't safe anywhere still gets blocked as a whole name.
const exact = [...words.filter((w) => w.scope !== 'both').map((w) => w.word), ...slurs.filter((w) => !safeAnywhere(w))];

const quote = (w) => `'${w.replace(/'/g, "''")}'`;

// normalise_name() is applied on the way in so the stored pattern is in the
// same shape a submitted name gets reduced to — "s p a m", "s-p-a-m" and
// "5pam" all have to meet the one entry "spam".
function insert(list, match) {
  return [
    `-- ${list.length} ${match} patterns`,
    'insert into public.blocked_names (pattern, match)',
    `select distinct public.normalise_name(w), '${match}'`,
    `from unnest(array[`,
    '  ' + list.map(quote).join(',\n  '),
    ']) w',
    "where public.normalise_name(w) <> ''",
    'on conflict (pattern) do nothing;',
    '',
  ].join('\n');
}

console.log('-- Generated by npm run name-blocklist. Paste into the Supabase SQL editor.');
console.log('-- Sources: English Speller Database (© Kevin Atkinson) and LDNOOBW (CC BY 4.0).');
console.log('-- Safe to re-run: every insert is on conflict do nothing.');
console.log();
console.log(insert(substring, 'substring'));
console.log(insert(exact, 'exact'));
console.error(
  `emitted ${substring.length} substring + ${exact.length} exact patterns`
);
